const assert = require("node:assert/strict")
const fs = require("node:fs")
const path = require("node:path")
const { cleanTechnicalText, dominantDirection, withPersianFont } = require("../runtime/runtime.js")

assert.equal(dominantDirection("T3 Code یک ابزار هوشمند برای برنامه‌نویسی است"), "rtl")
assert.equal(dominantDirection("T3 Code is a fast coding assistant"), "ltr")
assert.equal(dominantDirection("https://example.com/english/path این یک متن فارسی است"), "rtl")
assert.equal(dominantDirection("C:\\Users\\Name\\project این مسیر درست است"), "rtl")
assert.equal(dominantDirection("test@example.com این ایمیل معتبر است"), "rtl")
assert.equal(dominantDirection("commit 3f9a2c1d0b را بررسی کن"), "rtl")
assert.equal(dominantDirection("1234 — ..."), null)
assert.equal(dominantDirection("ab اب"), "rtl")
assert.equal(dominantDirection("This paragraph is mostly English with one فارسی word."), "rtl")
assert.equal(dominantDirection("Run npm test and check the output, then ب"), "rtl")
assert.equal(dominantDirection("Only English here, with a URL https://example.com/فارسی"), "ltr")
assert.equal(cleanTechnicalText("before https://example.com/a after").trim(), "before   after")

const defaultSans = '-apple-system, BlinkMacSystemFont, "Segoe UI", system-ui, sans-serif'
assert.equal(withPersianFont(""), `"T3 Persian", ${defaultSans}`)
assert.equal(withPersianFont(null), `"T3 Persian", ${defaultSans}`)
assert.equal(withPersianFont('"Inter", sans-serif'), '"T3 Persian", "Inter", sans-serif')
assert.equal(withPersianFont('"T3 Persian", "Inter"'), '"T3 Persian", "Inter"')

const root = path.resolve(__dirname, "..")
const runtime = fs.readFileSync(path.join(root, "runtime", "runtime.js"), "utf8")
const css = fs.readFileSync(path.join(root, "runtime", "runtime.css"), "utf8")
const installer = fs.readFileSync(path.join(root, "install.ps1"), "utf8")
const uninstaller = fs.readFileSync(path.join(root, "uninstall.ps1"), "utf8")
const watcher = fs.readFileSync(path.join(root, "watch.ps1"), "utf8")
const pkg =JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"))

assert.equal(/const VERSION = "([^"]+)"/.exec(runtime)[1], pkg.version, "runtime and package versions differ")
assert.match(runtime, /MutationObserver/)
assert.match(runtime, /requestAnimationFrame/)
assert.doesNotMatch(runtime, /setInterval/)
assert.doesNotMatch(runtime, /fetch\(|XMLHttpRequest|WebSocket|console\./)
assert.match(runtime, /COMPOSER_SELECTOR = '\[data-testid="composer-editor"\]'/)
assert.match(runtime, /\.chat-markdown/)
assert.match(runtime, /\[data-timeline-root\]/)
assert.match(runtime, /\[data-user-message-body\]/)
assert.match(runtime, /\[data-markdown-details-summary\], \[data-markdown-details-content\]/, "folded sections must get a direction like paragraphs")
assert.match(css, /Vazirmatn\.woff2/)
assert.match(css, /unicode-range/)
assert.doesNotMatch(css, /--font-mono\s*:/)
assert.match(css, /\[data-t3pt-label\]\s*\{[^}]*unicode-bidi/s)
assert.doesNotMatch(css.match(/\[data-t3pt-label\]\s*\{[^}]*\}/s)[0], /text-align/)
assert.match(installer, /server\.asar/)
assert.match(installer, /server\.asar\.backup/)
assert.match(installer, /asar-patch\.mjs/)
assert.doesNotMatch(installer, /remote-debugging|NODE_OPTIONS/)
assert.match(installer, /MoveFileEx\(\$temp, \$serverAsar, 0x1 -bor 0x8\)/, "server.asar must be swapped atomically")
assert.match(installer, /\[IO\.FileShare\]::Read\)/, "installer must block writers while reading")
assert.match(installer, /Register-ScheduledTask/)
assert.match(watcher, /Invoke-Patcher @\("prepare", /, "the watcher must prepare the patch ahead of the swap")
assert.match(watcher, /MoveFileEx\(/, "the watcher must swap atomically")
assert.match(watcher, /FileShare\]"ReadWrite, Delete"/, "the watcher must never block the updater while reading")
assert.doesNotMatch(watcher, /FileShare\]::Read\)/, "the watcher must never lock out the updater")
assert.match(watcher, /Threading\.Mutex/)
assert.match(watcher, /IncludeSubdirectories = \$true/)
assert.doesNotMatch(watcher, /Stop-Process|\.Kill\(/, "the watcher must never close T3 Code")
assert.match(uninstaller, /Unregister-ScheduledTask/)
assert.match(uninstaller, /originalSha256/)
assert.match(uninstaller, /Refusing to restore a backup from a different build/)

console.log("All runtime checks passed.")
